async function main() {
  const adminPassword = await bcrypt.hash("Admin@1234", 10);
  const pharmPassword = await bcrypt.hash("Pharm@1234", 10);
  const custPassword = await bcrypt.hash("User@1234", 10);

  await prisma.user.upsert({
    where: { email: "admin@levanalifecare.com" },
    update: {},
    create: {
      name: "Store Administrator",
      email: "admin@levanalifecare.com",
      phone: "+919876543210",
      password: adminPassword,
      role: Role.ADMIN,
    },
  });

  await prisma.user.upsert({
    where: { email: "pharmacist@levanalifecare.com" },
    update: {},
    create: {
      name: "Registered Pharmacist",
      email: "pharmacist@levanalifecare.com",
      phone: "+919876543211",
      password: pharmPassword,
      role: Role.PHARMACIST,
    },
  });

  const customer = await prisma.user.upsert({
    where: { email: "customer@levanalifecare.com" },
    update: {},
    create: {
      name: "Aditi Sharma",
      email: "customer@levanalifecare.com",
      phone: "+919876543212",
      password: custPassword,
      role: Role.CUSTOMER,
      addresses: {
        create: {
          recipient: "Aditi Sharma",
          phone: "+919876543212",
          street: "Flat 402, Green Park Enclave, Delhi Road",
          city: "Meerut",
          state: "Uttar Pradesh",
          pincode: "250002",
          isDefault: true,
        },
      },
    },
  });

  for (const item of PRODUCTS) {
    const product = await prisma.product.upsert({
      where: { slug: item.slug },
      update: {
        price: item.price,
        mrp: item.mrp,
        discount: item.discount,
        scheduleClass: item.scheduleClass,
        requiresRx: item.requiresRx,
      },
      create: {
        name: item.name,
        slug: item.slug,
        salt: item.salt,
        company: item.company,
        category: item.category,
        pack: item.pack,
        price: item.price,
        mrp: item.mrp,
        discount: item.discount,
        scheduleClass: item.scheduleClass,
        requiresRx: item.requiresRx,
        tag: item.tag,
        icon: item.icon,
        photo: item.photo,
        hsnCode: "3004",
        gstRate: 12.0,
      },
    });

    const existingBatches = await prisma.inventoryBatch.count({
      where: { productId: product.id },
    });

    if (existingBatches === 0) {
      const expiryDate = new Date();
      expiryDate.setFullYear(expiryDate.getFullYear() + 2);

      await prisma.inventoryBatch.create({
        data: {
          productId: product.id,
          batchNumber: `BTH-${product.slug.toUpperCase().slice(0, 4)}-26`,
          expiryDate,
          quantity: 100,
          mrp: product.mrp,
          purchasePrice: product.price * 0.7,
        },
      });
    }
  }

  console.log("Database seeded successfully with users, medicines, and inventory batches.");
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });

